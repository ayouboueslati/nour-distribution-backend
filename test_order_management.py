def test_confirm_order(order_id: str):
    """Test: Confirm order (should auto-generate devis)"""
    print("\n" + "="*80)
    print(f"TEST 4: Confirm Order {order_id} (Auto-generate Devis)")
    print("="*80)
    
    response = requests.post(
        f"{BASE_URL}/orders/{order_id}/confirm",
        headers=get_auth_headers()
    )
    
    print(f"Status: {response.status_code}")
    if response.status_code == 200:
        data = response.json()
        print(f"✅ Order confirmed!")
        print(f"   Status: {data['status']}")
        print(f"   Confirmed at: {data.get('confirmed_at', 'N/A')}")
        
        # Check if devis was generated by looking at order history
        print("\n   Checking for auto-generated devis...")
        history_response = requests.get(
            f"{BASE_URL}/orders/{order_id}/history",
            headers=get_auth_headers()
        )
        if history_response.status_code == 200:
            history = history_response.json()
            devis_entry = next((h for h in history if h['action'] == 'devis_generated'), None)
            if devis_entry:
                print(f"   ✅ Devis auto-generated: {json.loads(devis_entry['new_value'])['devis_number']}")
            else:
                print(f"   ⚠️  No devis generation found in history")
        
        return data
    else:
        print(f"❌ Failed: {response.text}")
        return None

