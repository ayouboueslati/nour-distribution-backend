import requests
import json
from datetime import datetime

BASE_URL = "http://localhost:8000/api/v1"

# You'll need to get a valid token first by logging in
# Replace this with your actual admin token
TOKEN = None

def get_auth_headers():
    if not TOKEN:
        print("⚠️  No token set. Please login first.")
        return {}
    return {"Authorization": f"Bearer {TOKEN}"}

def login(email: str, password: str):
    """Login and get token"""
    global TOKEN
    response = requests.post(
        f"{BASE_URL}/auth/login",
        json={"email": email, "password": password}
    )
    if response.status_code == 200:
        TOKEN = response.json()["access_token"]
        print(f"✅ Logged in successfully")
        return True
    else:
        print(f"❌ Login failed: {response.text}")
        return False

def test_get_orders():
    """Test: Get all orders"""
    print("\n" + "="*80)
    print("TEST 1: Get All Orders")
    print("="*80)
    
    response = requests.get(
        f"{BASE_URL}/orders/",
        headers=get_auth_headers()
    )
    
    print(f"Status: {response.status_code}")
    if response.status_code == 200:
        data = response.json()
        print(f"✅ Found {data['total']} orders")
        if data['orders']:
            print(f"First order: {data['orders'][0]['order_number']} - Status: {data['orders'][0]['status']}")
        return data['orders']
    else:
        print(f"❌ Failed: {response.text}")
        return []

def test_accept_order(order_id: str):
    """Test: Accept an order (PENDING → PROCESSING)"""
